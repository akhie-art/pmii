import DOMPurify from "isomorphic-dompurify";

const BASE_ALLOWED_TAGS = [
  "a", "abbr", "b", "blockquote", "br", "caption", "center", "code", "col",
  "colgroup", "dd", "del", "div", "dl", "dt", "em", "figcaption", "figure",
  "font", "h1", "h2", "h3", "h4", "h5", "h6", "hr", "i", "img", "ins",
  "li", "mark", "ol", "p", "pre", "q", "s", "small", "span", "strong",
  "sub", "sup", "table", "tbody", "td", "tfoot", "th", "thead", "tr", "u", "ul",
];

const BASE_ALLOWED_ATTR = [
  "align", "alt", "border", "cellpadding", "cellspacing", "class", "color",
  "colspan", "dir", "face", "height", "href", "id", "rel", "rowspan",
  "size", "src", "style", "target", "title", "valign", "width",
];

const LETTER_STRUCTURAL_TAGS = ["article", "footer", "header", "main", "section"];
const LETTER_SAFE_DATA_ATTRS = [
  "data-field",
  "data-placeholder",
  "data-borderless",
  "data-letter-meta",
  "data-letter-overlay",
];

const MONOTYPE_CORSIVA_FALLBACK_STACK =
  '"Monotype Corsiva", var(--font-corsiva, "Charm"), "Apple Chancery", "URW Chancery L", cursive';
const ARIAL_NARROW_FALLBACK_STACK =
  '"Arial Narrow", var(--font-arial-narrow, "Archivo Narrow"), "Liberation Sans Narrow", Arial, sans-serif';
const CALIBRI_FALLBACK_STACK =
  '"Calibri", "Aptos", var(--font-calibri, "Carlito"), "Liberation Sans", Arial, sans-serif';

function enhanceDocumentFontAndBorderCss(css: string): string {
  let out = css;
  if (/(?:monotype\s+corsiva|mt\s+corsiva|arial\s+narrow|\bcalibri\b|\baptos\b)/i.test(out)) {
    out = out.replace(
      /((?:font-family|--docx-[\w-]*font)\s*:\s*)([^;{}]+)(;?)/gi,
      (fullMatch, prefix: string, rawValue: string, suffix: string) => {
        const hasImportant = /!important\s*$/i.test(rawValue);
        let val = rawValue.replace(/\s*!important\s*$/i, "").trim();
        let changed = false;

        if (/monotype\s+corsiva|mt\s+corsiva/i.test(val) && !val.includes("--font-corsiva")) {
          val = val.replace(
            /(["']?)(?:monotype\s+corsiva|mt\s+corsiva)\1/gi,
            MONOTYPE_CORSIVA_FALLBACK_STACK
          );
          changed = true;
        }
        if (/arial\s+narrow/i.test(val) && !val.includes("--font-arial-narrow")) {
          val = val.replace(/(["']?)arial\s+narrow\1/gi, ARIAL_NARROW_FALLBACK_STACK);
          changed = true;
        }
        if (/\b(?:calibri|aptos)\b/i.test(val) && !val.includes("--font-calibri")) {
          val = val.replace(/(["']?)(?:calibri|aptos(?:\s+display)?)\1/gi, CALIBRI_FALLBACK_STACK);
          changed = true;
        }
        if (!changed) return fullMatch;
        return `${prefix}${val}${hasImportant ? " !important" : ""}${suffix}`;
      }
    );
  }
  if (/\bdouble\b/i.test(out)) {
    out = out.replace(
      /(border(?:-(?:top|bottom|left|right))?\s*:\s*)(\d+(?:\.\d+)?)(pt|px)(\s+double\b)/gi,
      (match, prefix: string, numStr: string, unit: string, rest: string) => {
        const val = parseFloat(numStr);
        if (Number.isNaN(val)) return match;
        const ptVal = unit.toLowerCase() === "px" ? val * 0.75 : val;
        return ptVal < 2.5 ? `${prefix}3pt${rest}` : match;
      }
    );
  }
  return out;
}

/**
 * Sanitizes CSS text inside `<style>` blocks generated by `docx-preview` so
 * Word layout rules (margins, fonts, tables) render intact while stripping
 * dangerous CSS constructs (`@import`, `expression()`, external `url()`, etc.).
 */
export function sanitizeDocumentCss(css: string): string {
  if (!css || typeof css !== "string") return "";

  const sanitized = css
    // Prevent opening HTML tags / </style> breakout while keeping CSS child combinators (>)
    .replace(/</g, "")
    // Strip CSS @import rules (blocks remote stylesheet loading / data exfiltration)
    .replace(/@import\b[^;{}]*(?:;|$)/gi, "")
    // Strip legacy IE/Mozilla script execution vectors in CSS
    .replace(/expression\s*\([^)]*\)/gi, "none")
    .replace(/behavior\s*:[^;{}]*(?:;|$)/gi, "")
    .replace(/-moz-binding\s*:[^;{}]*(?:;|$)/gi, "")
    .replace(/javascript\s*:/gi, "")
    .replace(/vbscript\s*:/gi, "")
    // Block external url(...) references while allowing safe inline data: image/font URIs
    .replace(
      /url\s*\(\s*(['"]?)\s*([^)'"]+?)\s*\1\s*\)/gi,
      (_match, _quote, rawTarget: string) => {
        const target = rawTarget.trim();
        if (/^data:(?:image\/(?:png|jpe?g|gif|webp|bmp|x-icon)|font\/|application\/(?:font-|x-font-|vnd\.ms-fontobject))/i.test(target)) {
          return `url("${target}")`;
        }
        return "none";
      }
    );

  return enhanceDocumentFontAndBorderCss(sanitized);
}

/**
 * Sanitizes rich HTML content (articles, general editor HTML)
 * to prevent Cross-Site Scripting (XSS) while preserving safe document styling.
 */
export function sanitizeHtml(dirty: string | null | undefined): string {
  if (!dirty || typeof dirty !== "string") return "";

  return DOMPurify.sanitize(dirty, {
    ALLOWED_TAGS: BASE_ALLOWED_TAGS,
    ALLOWED_ATTR: BASE_ALLOWED_ATTR,
    ALLOW_DATA_ATTR: false,
    FORBID_TAGS: ["script", "style", "iframe", "object", "embed", "form", "input", "button", "textarea", "select"],
    FORBID_ATTR: ["onerror", "onload", "onclick", "onmouseover", "onfocus", "onblur"],
  });
}

export interface SanitizeLetterOptions {
  /** Preserve safe internal letter canvas attributes (`data-field`, `data-placeholder`, `data-borderless`). */
  preservePlaceholders?: boolean;
  /** Preserve `docx-preview` layout tags (`section`, `article`, `header`, `footer`) and sanitized `<style>` blocks. */
  preserveDocxLayout?: boolean;
}

/**
 * Sanitizes official letter / DOCX preview HTML while keeping safe structural layout
 * and/or live-editor placeholder markers intact without reintroducing XSS vectors.
 */
export function sanitizeLetterHtml(
  dirty: string | null | undefined,
  options: SanitizeLetterOptions = {}
): string {
  if (!dirty || typeof dirty !== "string") return "";

  const { preservePlaceholders = false, preserveDocxLayout = true } = options;

  const allowedTags = preserveDocxLayout
    ? [...BASE_ALLOWED_TAGS, ...LETTER_STRUCTURAL_TAGS, "style"]
    : [...BASE_ALLOWED_TAGS, ...LETTER_STRUCTURAL_TAGS];

  const allowedAttr = preservePlaceholders
    ? [...BASE_ALLOWED_ATTR, ...LETTER_SAFE_DATA_ATTRS]
    : [...BASE_ALLOWED_ATTR, "data-borderless", "data-letter-meta", "data-letter-overlay"];

  const forbidTags = preserveDocxLayout
    ? ["script", "iframe", "object", "embed", "form", "input", "button", "textarea", "select"]
    : ["script", "style", "iframe", "object", "embed", "form", "input", "button", "textarea", "select"];

  const clean = DOMPurify.sanitize(dirty, {
    ALLOWED_TAGS: allowedTags,
    ALLOWED_ATTR: allowedAttr,
    ALLOW_DATA_ATTR: false,
    FORCE_BODY: preserveDocxLayout,
    FORBID_TAGS: forbidTags,
    FORBID_ATTR: ["onerror", "onload", "onclick", "onmouseover", "onfocus", "onblur"],
  });

  if (!preserveDocxLayout) {
    return clean;
  }

  let result = clean
    .replace(/<style\b[^>]*>([\s\S]*?)<\/style>/gi, (_match, cssBody: string) => {
      const safeCss = sanitizeDocumentCss(cssBody);
      return safeCss.trim() ? `<style>${safeCss}</style>` : "";
    })
    .replace(/(\bstyle=")([^"]*)(")/gi, (fullMatch, open: string, styleBody: string, close: string) => {
      if (!/(?:monotype\s+corsiva|mt\s+corsiva|arial\s+narrow|\bcalibri\b|\baptos\b|\bdouble\b)/i.test(styleBody)) {
        return fullMatch;
      }
      const decoded = styleBody
        .replace(/&quot;/gi, '"')
        .replace(/&#(?:39|x27);/gi, "'");
      const enhancedStyle = enhanceDocumentFontAndBorderCss(decoded).replace(/"/g, "'");
      return `${open}${enhancedStyle}${close}`;
    })
    .replace(/(\bstyle=')([^']*)(')/gi, (fullMatch, open: string, styleBody: string, close: string) => {
      if (!/(?:monotype\s+corsiva|mt\s+corsiva|arial\s+narrow|\bcalibri\b|\baptos\b|\bdouble\b)/i.test(styleBody)) {
        return fullMatch;
      }
      const decoded = styleBody
        .replace(/&quot;/gi, '"')
        .replace(/&#(?:39|x27);/gi, "'");
      const enhancedStyle = enhanceDocumentFontAndBorderCss(decoded).replace(/'/g, '"');
      return `${open}${enhancedStyle}${close}`;
    });

  // Perbaiki HTML arsip lama hasil docx-preview di mana parser HTML5 memecah
  // `<p><span><div style="...display:inline-block..."><img></div></span></p>`
  // menjadi `<p><span></span></p><div><img></div><p></p>` yang menambah baris kosong atas & bawah logo/QR.
  if (result.includes("docx-wrapper")) {
    result = result.replace(
      /<p\b([^>]*)>(?:\s*<span\b[^>]*>\s*<\/span>)*\s*<\/p>\s*<div\b([^>]*\bdisplay\s*:\s*inline-block[^>]*)>((?:(?!<div\b)[\s\S])*?)<\/div>(?:\s*<p\b[^>]*>\s*<\/p>)?/gi,
      (_match, pAttrs: string, divAttrs: string, inner: string) => {
        const alignMatch = pAttrs.match(/text-align\s*:\s*(left|center|right)/i);
        const alignCss = alignMatch ? `text-align:${alignMatch[1]};` : "";
        return `<p style="${alignCss}margin:0;line-height:0;font-size:0;min-height:0"><span${divAttrs}>${inner}</span></p>`;
      }
    );
  }

  return result;
}

/**
 * Escapes plain text for safe interpolation into HTML templates.
 */
export function escapeHtml(text: unknown): string {
  return String(text ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
